def test_safe_resolve_path(temp_server_dir):
    # Valid file resolution
    valid_path = config_service.safe_resolve_path("server.properties")
    assert valid_path == os.path.abspath(os.path.join(temp_server_dir, "server.properties"))

    # Path traversal attempt
    with pytest.raises(HTTPException) as exc_info:
        config_service.safe_resolve_path("../../etc/passwd")
    assert exc_info.value.status_code == status.HTTP_400_BAD_REQUEST
    assert "Path traversal attempt detected" in exc_info.value.detail

